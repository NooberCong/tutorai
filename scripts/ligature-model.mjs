// Builds src/lib/ligatureModel.ts — the word list and letter-pair table
// src/lib/ligatures.ts uses to tell which ligature a PDF left unmapped —
// from public-domain Project Gutenberg books (downloaded once, cached in the
// OS temp dir). Run: node scripts/ligature-model.mjs
import { mkdirSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const BOOKS = [
  11, 16, 23, 35, 36, 43, 46, 55, 74, 76, 84, 98, 120, 132, 145, 158, 160, 174, 205, 219, 345, 768, 829,
  1228, 1232, 1250, 1260, 1399, 1400, 1497, 1998, 2554, 2680, 2701, 2814, 3207, 4300, 4363, 7370, 10615,
  15776, 18269, 25344, 28054,
];
const MIN_COUNT = 3;

const cache = join(tmpdir(), "tutorai-gutenberg");
mkdirSync(cache, { recursive: true });
const counts = new Map();
for (const id of BOOKS) {
  const file = join(cache, `pg${id}.txt`);
  if (!existsSync(file)) {
    const res = await fetch(`https://www.gutenberg.org/cache/epub/${id}/pg${id}.txt`);
    if (!res.ok) throw new Error(`book ${id}: HTTP ${res.status}`);
    writeFileSync(file, await res.text());
  }
  let text = readFileSync(file, "utf8");
  const a = text.indexOf("*** START");
  const b = text.indexOf("*** END");
  text = text.slice(a > 0 ? a : 0, b > 0 ? b : undefined);
  for (const w of text.toLowerCase().match(/[a-z]+/g) ?? []) counts.set(w, (counts.get(w) ?? 0) + 1);
}

const words = [...counts]
  .filter(([w, n]) => n >= MIN_COUNT && w.length >= 3 && /ff|fi|fl|^th/.test(w))
  .sort((x, y) => y[1] - x[1] || (x[0] < y[0] ? -1 : 1))
  .map(([w]) => w);

// -ln P(next | prev) over word tokens, add-0.1 smoothed, in fifths of a nat
// as one base-62 digit (capped at 61).
const FROM = "^abcdefghijklmnopqrstuvwxyz";
const TO = "abcdefghijklmnopqrstuvwxyz$";
const DIGITS = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";
const pair = FROM.split("").map(() => new Array(TO.length).fill(0));
for (const [w, n] of counts) {
  const s = `^${w}$`;
  for (let i = 1; i < s.length; i++) pair[FROM.indexOf(s[i - 1])][TO.indexOf(s[i])] += n;
}
let bigrams = "";
for (const row of pair) {
  const total = row.reduce((x, y) => x + y, 0);
  for (const n of row) {
    const cost = -Math.log((n + 0.1) / (total + 0.1 * TO.length));
    bigrams += DIGITS[Math.min(61, Math.round(cost * 5))];
  }
}

writeFileSync(
  new URL("../src/lib/ligatureModel.ts", import.meta.url),
  `// Generated by scripts/ligature-model.mjs from public-domain Project
// Gutenberg books — do not edit.

/** Words with ff, fi or fl, or starting with th, most frequent first. */
export const WORDS = ${JSON.stringify(words.join(" "))};

/** -ln P(next letter | previous), in fifths of a nat as one base-62 digit:
 *  a row per previous in "${FROM}" (^ = word start), a column per next in
 *  "${TO}" ($ = word end). */
export const BIGRAMS = ${JSON.stringify(bigrams)};
`,
);
console.log(`${words.length} words, ${bigrams.length} pair costs`);
